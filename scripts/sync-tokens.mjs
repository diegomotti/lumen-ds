import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildTokenCatalog } from "./token-catalog.mjs";

const outputFile = fileURLToPath(new URL("../src/tokens.lumen.css", import.meta.url));

function aliasFor(name) {
    if (name.startsWith("--pp-font-size-")) {
        return `--text-pp-${name.slice("--pp-font-size-".length).replace(/^text-/, "")}`;
    }
    for (const [prefix, aliasPrefix] of [
        ["--pp-palette-", "--color-pp-palette-"],
        ["--pp-color-", "--color-pp-"],
        ["--pp-font-family-", "--font-pp-"],
        ["--pp-font-tracking-", "--tracking-pp-"],
        ["--pp-shape-", "--radius-pp-"],
    ]) {
        if (name.startsWith(prefix)) return aliasPrefix + name.slice(prefix.length);
    }
    return null;
}

const { collections } = buildTokenCatalog();
const tokens = collections.flatMap((collection) => collection.tokens);
const darkTokens = tokens.filter((token) => token.dark !== token.light);
const aliases = tokens.map((token) => ({ token, alias: aliasFor(token.name) })).filter(({ alias }) => alias);
const blocks = collections.filter((collection) => collection.tokens.length).map((collection) =>
    `  /* ${collection.name} */\n${collection.tokens.map((token) => `  ${token.name}: ${token.light};`).join("\n")}`
).join("\n\n");

const css = [
    "/* Generated by scripts/sync-tokens.mjs from resources/tokens.json. Do not edit. */",
    "",
    ":root {",
    "  color-scheme: light;",
    "",
    blocks,
    "}",
    "",
    '[data-theme="dark"] {',
    "  color-scheme: dark;",
    ...darkTokens.map((token) => `  ${token.name}: ${token.dark};`),
    "}",
    "",
    "/* Tailwind CSS v4 theme aliases. */",
    "@theme inline {",
    ...aliases.map(({ token, alias }) => `  ${alias}: var(${token.name});`),
    "}",
    "",
].join("\n");

writeFileSync(outputFile, css, "utf8");
console.log(`tokens.lumen.css: ${tokens.length} tokens, ${darkTokens.length} dark overrides, ${aliases.length} aliases`);
